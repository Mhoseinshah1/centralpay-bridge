"""scripts/render-caddy-config.sh — safe managed-config upgrade for the
installed Caddyfile (production incident: an already-running installation's
/etc/centralpay-bridge/Caddyfile was never regenerated by `centralpay
update`, nor by install.sh's "keep existing configuration" rerun path, so a
security-relevant template change like Referer ct/sig log redaction could
ship in source but never reach production).

Deterministic subprocess tests — no root, no real Docker daemon required for
this file. `docker` on PATH is replaced with a wrapper that records its
invocation and returns a scripted exit code, so these tests exercise the
SCRIPT's own control flow (extraction, rendering, diffing, backup, atomic
replace, exit-code contract) independent of Caddy's actual parser -- that
real-parser correctness is covered separately by the `@pytest.mark.docker`
tests below (gated on a real Docker daemon) and by the existing
`.github/workflows/ci.yml` "docker" job, which runs the real `caddy:2`
image directly.
"""

