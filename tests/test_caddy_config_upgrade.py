def _write_fake_docker(bindir: Path, *, validate_ok: bool = True) -> Path:
    """A `docker` stub on PATH: records every invocation and exits
    according to `validate_ok` -- fast and deterministic, independent of
    whether a real Docker daemon or the caddy:2 image is available."""
    call_log = bindir / "docker_calls.log"
    script = bindir / "docker"
    body = f'printf "%s\\n" "$*" >> {shlex.quote(str(call_log))}\n'
    body += "exit 0\n" if validate_ok else 'echo "fake caddy validate: syntax error" >&2\nexit 1\n'
    script.write_text("#!/usr/bin/env bash\n" + body)
    script.chmod(0o755)
    return call_log


@pytest.fixture
def sandbox(tmp_path):
    install = tmp_path / "install"
    config = tmp_path / "config"
    bindir = tmp_path / "bin"
